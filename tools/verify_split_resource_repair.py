#!/usr/bin/env python3
"""Verify Meboard's density-split resource reconstruction.

The repair manifest is generated by the split-resource merger and records each
public resource declaration plus every decoded XML attribute restored from a
raw compiled resource ID. This verifier does not infer correctness from file
counts alone: it checks every expected declaration and source replacement, and
optionally checks a compiled APK using aapt2 dump output captured by the build.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import xml.etree.ElementTree as ET
from collections import Counter
from pathlib import Path
from typing import Any

EXPECTED_PUBLIC_IDS = 114
EXPECTED_REFERENCES = 194
EXPECTED_XML_FILES = 48
ANDROID_NS = "{http://schemas.android.com/apk/res/android}"


def fail(message: str) -> None:
    raise SystemExit(message)


def load_json(path: Path) -> dict[str, Any]:
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        fail(f"cannot load manifest {path}: {exc}")
    if not isinstance(value, dict):
        fail("repair manifest must be a JSON object")
    return value


def normalize_id(value: str) -> str:
    value = value.strip().lower()
    if not value.startswith("0x"):
        fail(f"resource ID is not hexadecimal: {value!r}")
    return f"0x{int(value, 16):08x}"


def public_index(path: Path) -> dict[tuple[str, str], str]:
    try:
        root = ET.parse(path).getroot()
    except (OSError, ET.ParseError) as exc:
        fail(f"cannot parse {path}: {exc}")
    result: dict[tuple[str, str], str] = {}
    ids: dict[str, tuple[str, str]] = {}
    for node in root.findall("public"):
        kind = node.attrib.get("type")
        name = node.attrib.get("name")
        rid = node.attrib.get("id")
        if not kind or not name or not rid:
            fail(f"malformed public declaration in {path}: {node.attrib}")
        key = (kind, name)
        value = normalize_id(rid)
        if key in result and result[key] != value:
            fail(f"duplicate public name with different IDs: {key}")
        if value in ids and ids[value] != key:
            fail(f"resource ID collision {value}: {ids[value]} vs {key}")
        result[key] = value
        ids[value] = key
    return result


def occurrence_count(text: str, value: str) -> int:
    return text.count(value)


def verify_source_references(root: Path, references: list[dict[str, Any]]) -> set[str]:
    by_file: dict[str, list[dict[str, Any]]] = {}
    for item in references:
        rel = item.get("file")
        if not isinstance(rel, str) or not rel:
            fail(f"reference record has no file: {item}")
        by_file.setdefault(rel, []).append(item)

    for rel, records in by_file.items():
        path = root / rel
        if not path.is_file():
            fail(f"repaired XML is missing: {rel}")
        text = path.read_text(encoding="utf-8", errors="strict")
        for record in records:
            expected = record.get("expected")
            before = record.get("before", "@null")
            count = record.get("expected_occurrences", 1)
            if not isinstance(expected, str) or not expected.startswith("@"):
                fail(f"invalid expected reference in {rel}: {record}")
            if not isinstance(count, int) or count < 1:
                fail(f"invalid occurrence count in {rel}: {record}")
            if occurrence_count(text, expected) < count:
                fail(
                    f"{rel}: expected at least {count} occurrence(s) of "
                    f"{expected!r}, found {occurrence_count(text, expected)}"
                )
            # The manifest may list several replaced attributes from one file.
            # A remaining @null anywhere in an affected XML is never accepted.
            if isinstance(before, str) and before == "@null" and "@null" in text:
                fail(f"{rel}: unresolved @null remains after split-resource repair")
    return set(by_file)


def verify_compiled_evidence(path: Path, references: list[dict[str, Any]]) -> None:
    evidence = load_json(path)
    if evidence.get("status") not in ("passed", "success", "complete"):
        fail(f"compiled-resource evidence did not pass: {evidence.get('status')!r}")
    compiled = evidence.get("references")
    if not isinstance(compiled, list):
        fail("compiled-resource evidence has no references list")
    expected_keys = {
        (item.get("file"), item.get("attribute"), normalize_id(str(item.get("resource_id"))))
        for item in references
    }
    actual_keys: set[tuple[Any, Any, str]] = set()
    for item in compiled:
        raw = item.get("resource_id")
        if raw is None:
            fail(f"compiled record lacks resource ID: {item}")
        rid = normalize_id(str(raw))
        if int(rid, 16) == 0:
            fail(f"compiled reference became numeric zero: {item}")
        raw_value = str(item.get("raw_value", ""))
        if raw_value in ("0", "@0", "@0x00000000"):
            fail(f"compiled reference retained zero/name-0 value: {item}")
        actual_keys.add((item.get("file"), item.get("attribute"), rid))
    missing = sorted(expected_keys - actual_keys, key=repr)
    if missing:
        fail(f"compiled-resource evidence is missing {len(missing)} repaired entries: {missing[:20]}")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--buildtree",
        type=Path,
        default=Path("/mnt/data/meboard_work/buildtree"),
    )
    parser.add_argument(
        "--manifest",
        type=Path,
        default=Path("/mnt/data/meboard_work/reports/split-resource-repair.json"),
    )
    parser.add_argument("--compiled-evidence", type=Path)
    args = parser.parse_args()

    if not args.buildtree.is_dir():
        fail(f"decoded Meboard tree is missing: {args.buildtree}")
    manifest = load_json(args.manifest)
    public = manifest.get("public_resources")
    references = manifest.get("references")
    if not isinstance(public, list) or not isinstance(references, list):
        fail("manifest must contain public_resources and references arrays")

    if len(public) != EXPECTED_PUBLIC_IDS:
        fail(f"expected {EXPECTED_PUBLIC_IDS} split public IDs, found {len(public)}")
    if len(references) != EXPECTED_REFERENCES:
        fail(f"expected {EXPECTED_REFERENCES} repaired references, found {len(references)}")

    declared = public_index(args.buildtree / "res/values/public.xml")
    seen_ids: Counter[str] = Counter()
    for item in public:
        kind = item.get("type")
        name = item.get("name")
        rid = normalize_id(str(item.get("id")))
        if declared.get((kind, name)) != rid:
            fail(
                f"public.xml mismatch for {kind}/{name}: "
                f"expected {rid}, found {declared.get((kind, name))}"
            )
        seen_ids[rid] += 1
    duplicates = [rid for rid, count in seen_ids.items() if count != 1]
    if duplicates:
        fail(f"repair manifest repeats split resource IDs: {duplicates}")

    files = verify_source_references(args.buildtree, references)
    if len(files) != EXPECTED_XML_FILES:
        fail(f"expected {EXPECTED_XML_FILES} repaired XML files, found {len(files)}")

    # A zero can be legitimate text or a dimension. Reject only explicit broken
    # resource forms and the exact runtime-producing name-based form recorded by
    # the repair manifest.
    bad_patterns = (
        re.compile(r'="@null"'),
        re.compile(r'="@0(?:x0{1,8})?"', re.I),
    )
    for rel in files:
        text = (args.buildtree / rel).read_text(encoding="utf-8")
        for pattern in bad_patterns:
            if pattern.search(text):
                fail(f"{rel}: broken zero/null resource reference remains")

    if args.compiled_evidence:
        verify_compiled_evidence(args.compiled_evidence, references)

    print(
        "split-resource repair verified: "
        f"{len(public)} original IDs, {len(references)} references, "
        f"{len(files)} XML files; no null/zero resource reference"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
